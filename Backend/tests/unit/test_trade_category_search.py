def test_category_terms_electrical_contractors():
    """Verify electrical contractors generates contractor variations and trade aliases."""
    contractor_terms, non_contractor_terms = category_term_variations("electrical contractors")

    # Contractor variations must include electrical and aliases with 'contractor'
    assert "electrical contractors" in contractor_terms
    assert "electrical contractor" in contractor_terms
    assert any("electric" in t and "contractor" in t for t in contractor_terms)
    assert any("wiring" in t and "contractor" in t for t in contractor_terms)

    # Non-contractor terms must include the base trade and aliases without 'contractor'
    assert "electrical" in non_contractor_terms
    assert "electrician" in non_contractor_terms or "electric" in non_contractor_terms
    assert "wiring" in non_contractor_terms

    # category_terms must combine both without duplicates
    all_terms = category_terms("electrical contractors")
    assert len(all_terms) == len(set(all_terms))
    assert set(contractor_terms).issubset(set(all_terms))
    assert set(non_contractor_terms).issubset(set(all_terms))


