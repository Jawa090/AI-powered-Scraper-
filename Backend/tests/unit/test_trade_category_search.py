def test_search_leads_contractor_prioritization_across_pages(db_session):
    """
    Verify:
    When 2 contractor leads and 2 alias/non-contractor leads exist:
    - Page 1 (limit=2, offset=0) returns both contractor leads.
    - Page 2 (limit=2, offset=2) returns both alias leads.
    - Total is 4.
    """
    from services.ingest import upsert_leads

    # Contractor leads (older created_at)
    r1 = {
        "source_code": "jwiz",
        "record_kind": "company",
        "external_id": "ext-p1-" + uuid.uuid4().hex[:8],
        "organization_name": "Alpha Electrical Contractors",
        "category": "Electrical Contractors",
        "us_state": "NY",
        "city": "Albany",
    }
    r2 = {
        "source_code": "jwiz",
        "record_kind": "company",
        "external_id": "ext-p2-" + uuid.uuid4().hex[:8],
        "organization_name": "Beta Wiring Contractors",
        "category": "Wiring Contractors",
        "us_state": "NY",
        "city": "Albany",
    }
    # Non-contractor alias leads (newer created_at)
    r3 = {
        "source_code": "jwiz",
        "record_kind": "company",
        "external_id": "ext-p3-" + uuid.uuid4().hex[:8],
        "organization_name": "Gamma Electrician Solo",
        "category": "Electrician",
        "us_state": "NY",
        "city": "Albany",
    }
    r4 = {
        "source_code": "jwiz",
        "record_kind": "company",
        "external_id": "ext-p4-" + uuid.uuid4().hex[:8],
        "organization_name": "Delta Electric Service",
        "category": "Electric",
        "us_state": "NY",
        "city": "Albany",
    }

    res = upsert_leads(db_session, [r1, r2, r3, r4])
    db_session.flush()

    c1_id, c2_id, nc1_id, nc2_id = res.lead_ids

    # Contractor leads get older timestamp, alias leads get newer timestamp
    db_session.get(Lead, c1_id).created_at = datetime(2025, 1, 1, tzinfo=timezone.utc)
    db_session.get(Lead, c2_id).created_at = datetime(2025, 1, 2, tzinfo=timezone.utc)
    db_session.get(Lead, nc1_id).created_at = datetime(2026, 1, 1, tzinfo=timezone.utc)
    db_session.get(Lead, nc2_id).created_at = datetime(2026, 1, 2, tzinfo=timezone.utc)
    db_session.flush()

    repo = Repositories(db_session).leads

    # Page 1: limit=2, offset=0
    page1, total1 = repo.search_leads(
        category="electrical contractors",
        us_state="NY",
        record_kind="company",
        limit=2,
        offset=0,
    )
    assert total1 == 4
    page1_ids = [l.id for l in page1]
    assert len(page1_ids) == 2
    assert set(page1_ids) == {c1_id, c2_id}

    # Page 2: limit=2, offset=2
    page2, total2 = repo.search_leads(
        category="electrical contractors",
        us_state="NY",
        record_kind="company",
        limit=2,
        offset=2,
    )
    assert total2 == 4
    page2_ids = [l.id for l in page2]
    assert len(page2_ids) == 2
    assert set(page2_ids) == {nc1_id, nc2_id}


